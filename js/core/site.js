/* Mirage core: the <head> of an exported page and the sitemap. Shared by the editor and the CLI. */
import { esc } from './markup.js';

/* m: {title, description, url, lang}; page: 'our-loaves.html' or '' for the home page; og: 'assets/x.jpg' or '' */
export function headHTML(m, page, og, cssHref){
  const abs = p => m.url ? m.url+'/'+String(p).replace(/^\//,'') : p;
  return '<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n'+
    '<title>'+esc(m.title)+'</title>\n'+
    (m.description ? '<meta name="description" content="'+esc(m.description)+'">\n' : '')+
    (m.url ? '<link rel="canonical" href="'+esc(abs(page))+'">\n' : '')+
    '<meta property="og:type" content="website">\n<meta property="og:title" content="'+esc(m.title)+'">\n'+
    (m.description ? '<meta property="og:description" content="'+esc(m.description)+'">\n' : '')+
    (m.url ? '<meta property="og:url" content="'+esc(abs(page))+'">\n' : '')+
    (og ? '<meta property="og:image" content="'+esc(abs(og))+'">\n<meta name="twitter:card" content="summary_large_image">\n' : '')+
    '<link rel="stylesheet" href="'+cssHref+'">\n';
}
export function pageHTML(m, page, og, body, mainClass){
  return '<!DOCTYPE html>\n<html lang="'+esc(m.lang||'en')+'">\n<head>\n'+headHTML(m, page, og, 'mirage.css')+'</head>\n<body>\n'+
    '<!-- generated by Mirage -->\n<main class="'+mainClass+'">\n'+(body || '  <!-- empty page -->')+'\n</main>\n</body>\n</html>\n';
}
export function sitemapXML(url, paths){
  const x = s => String(s).replace(/[<>&'"]/g, c => ({'<':'&lt;','>':'&gt;','&':'&amp;',"'":'&apos;','"':'&quot;'}[c]));
  return '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'+
    paths.map(p => '  <url><loc>'+x(url+'/'+p)+'</loc></url>').join('\n')+'\n</urlset>\n';
}
export const robotsTXT = url => 'User-agent: *\nAllow: /\n'+(url ? 'Sitemap: '+url+'/sitemap.xml\n' : '');
